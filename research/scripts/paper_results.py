# ---------- loaders ----------
_sc = {}


def sc(key):
    """(mean NLL, mean NLL mixed with the n-gram cache) from the per-token file of one run."""
    if key not in _sc:
        _sc[key] = scores(key, CB, CQ)
    return _sc[key]


def arm(prefix, seeds=S8, cache=False):
    return np.array([sc(f"{prefix}-s{s}")[1 if cache else 0] for s in seeds])


def log(key):
    f = glob.glob(f"runs/{key}/*.jsonl")
    return [json.loads(line) for line in open(f[0])] if f else None


def final_loss(key):
    """Held-out loss at the last evaluation of a run (equals the post-eval mean where both exist)."""
    lines = log(key)
    if lines is None:
        return None
    ev = [d for d in lines if "step" in d and d.get("loss") is not None]
    return float(ev[-1]["loss"]) if ev else None


def curve(key):
    return {d["step"]: d["loss"] for d in log(key) if "step" in d and d.get("loss") is not None}


def head(key):
    return log(key)[0]


def last_eval(key):
    return [d for d in log(key) if "step" in d and d.get("loss") is not None][-1]


# ---------- statistics ----------
def cmp(a, b):
    d = np.asarray(a) - np.asarray(b)
    lo, hi = boot_ci(d)
    return dict(mean=d.mean(), lo=lo, hi=hi, med=float(np.median(d)), neg=int((d < 0).sum()), n=len(d),
                p=wilcoxon(d, alternative="less").pvalue, a=float(np.mean(a)), b=float(np.mean(b)))


# ---------- LaTeX formatting ----------
def f(x, nd=3, sign=False):
    return "$" + (f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}") + "$"


def ci(r, nd=3):
    return f"{f(r['mean'], nd, True)} [{f(r['lo'], nd, True)}, {f(r['hi'], nd, True)}]"


def mu(r, nd=3):
    return f(r["mean"], nd, True)


def br(r, nd=3):
    return f"{{\\scriptsize [{f(r['lo'], nd, True)}, {f(r['hi'], nd, True)}]}}"


def plain_ci(r, nd=4):
    return f"{r['mean']:+.{nd}f} [{r['lo']:+.{nd}f}, {r['hi']:+.{nd}f}], median {r['med']:+.{nd}f}, {r['neg']}/{r['n']} negative, p = {r['p']:.4f}"


def M(n):
    return f"{n / 1e6:.1f}M"


def write(name, lines):
    (OUT / name).write_text("% Generated by scripts/paper_results.py from runs/. Do not edit.\n" + "\n".join(lines) + "\n")


def tabular(name, spec, header, rows):
    body = ["\\begin{tabular}{" + spec + "}", "\\toprule", *header, "\\midrule"]
    for r in rows:
        body.append(r if isinstance(r, str) else " & ".join(r) + " \\\\")
    write(name, [*body, "\\bottomrule", "\\end{tabular}"])


def dat(name, cols, rows):
    (OUT / name).write_text(" ".join(cols) + "\n" + "\n".join(" ".join(f"{v:.6g}" for v in r) for r in rows) + "\n")


def npar(prefix, s=20):
    return head(f"{prefix}-s{s}")["n_params"]


